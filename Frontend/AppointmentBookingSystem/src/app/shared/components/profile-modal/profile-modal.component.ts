import { Component, EventEmitter, OnInit, OnDestroy, Input, Output, inject, signal, computed } from '@angular/core';
import { CommonModule } from '@angular/common';
import { FormBuilder, FormGroup, ReactiveFormsModule, Validators } from '@angular/forms';
import { AuthService } from '../../../core/services/auth.service';
import { UserDto, UpdateProfileRequest, ChangePasswordRequest } from '../../../core/models/auth.models';
import { OnlyDigitsDirective } from '../../directives';
import { AppInitialsPipe } from '../../pipes';
import { PHONE_10_DIGIT_REGEX, filter10Digits, getAvatarGradient } from '../../../core/constants/app.constants';

@Component({
  selector: 'app-profile-modal',
  standalone: true,
  imports: [CommonModule, ReactiveFormsModule, OnlyDigitsDirective, AppInitialsPipe],
  templateUrl: './profile-modal.component.html',
  styleUrls: ['./profile-modal.component.css']
})
export class ProfileModalComponent implements OnInit, OnDestroy {
  private readonly fb = inject(FormBuilder);
  readonly authService = inject(AuthService);
  readonly getAvatarGradient = getAvatarGradient;

  @Input() initialTab: 'profile' | 'security' = 'profile';
  @Output() close = new EventEmitter<void>();

  private closeTimer?: any;

  readonly currentUser = computed(() => this.authService.currentUser());
  readonly activeTab = signal<'profile' | 'security'>('profile');

  // Loading & Alert States
  readonly isSubmittingProfile = signal<boolean>(false);
  readonly isSubmittingPassword = signal<boolean>(false);
  readonly isUploadingAvatar = signal<boolean>(false);
  readonly alertMessage = signal<{ type: 'success' | 'error'; text: string } | null>(null);

  // Avatar Preview
  readonly previewAvatarUrl = signal<string | null>(null);

  // Password Visibility Toggles
  readonly showCurrentPassword = signal<boolean>(false);
  readonly showNewPassword = signal<boolean>(false);
  readonly showConfirmPassword = signal<boolean>(false);

  // Forms
  profileForm!: FormGroup;
  passwordForm!: FormGroup;

  ngOnInit(): void {
    const user = this.currentUser();

    if (this.initialTab === 'security' || user?.isPasswordAutoGenerated) {
      this.activeTab.set('security');
    } else {
      this.activeTab.set(this.initialTab || 'profile');
    }

    this.previewAvatarUrl.set(user?.profilePictureUrl || null);

    this.profileForm = this.fb.group({
      firstName: [user?.firstName || '', [Validators.required, Validators.minLength(2), Validators.maxLength(50)]],
      lastName: [user?.lastName || '', [Validators.maxLength(50)]],
      phoneNumber: [filter10Digits(user?.phoneNumber) || '', [Validators.required, Validators.pattern(PHONE_10_DIGIT_REGEX)]],
      profilePictureUrl: [user?.profilePictureUrl || null],
      address: [user?.address || '', [Validators.maxLength(200)]],
      city: [user?.city || '', [Validators.maxLength(100)]],
      state: [user?.state || '', [Validators.maxLength(100)]],
      postalCode: [user?.postalCode || '', [Validators.maxLength(20)]]
    });

    this.passwordForm = this.fb.group({
      currentPassword: ['', [Validators.required]],
      newPassword: ['', [Validators.required, Validators.minLength(6)]],
      confirmPassword: ['', [Validators.required]]
    }, { validators: this.passwordFormValidator.bind(this) });
  }

  private passwordFormValidator(group: FormGroup): { [key: string]: boolean } | null {
    const currentPass = group.get('currentPassword')?.value;
    const newPass = group.get('newPassword')?.value;
    const confirmPass = group.get('confirmPassword')?.value;

    const errors: { [key: string]: boolean } = {};

    if (currentPass && newPass && currentPass === newPass) {
      errors['sameAsCurrent'] = true;
    }

    if (confirmPass && newPass !== confirmPass) {
      errors['passwordMismatch'] = true;
    }

    return Object.keys(errors).length > 0 ? errors : null;
  }

  get isSameAsCurrentPassword(): boolean {
    const current = this.passwordForm?.get('currentPassword')?.value;
    const next = this.passwordForm?.get('newPassword')?.value;
    return !!current && !!next && current === next;
  }

  get isPasswordMismatch(): boolean {
    const next = this.passwordForm?.get('newPassword')?.value || '';
    const confirm = this.passwordForm?.get('confirmPassword')?.value || '';
    return !!confirm && next !== confirm;
  }

  get isPasswordMatch(): boolean {
    const next = this.passwordForm?.get('newPassword')?.value || '';
    const confirm = this.passwordForm?.get('confirmPassword')?.value || '';
    return !!confirm && !!next && next === confirm && next.length >= 6 && !this.isSameAsCurrentPassword;
  }

  setTab(tab: 'profile' | 'security'): void {
    this.activeTab.set(tab);
    this.alertMessage.set(null);
  }

  onAvatarFileSelected(event: Event): void {
    const input = event.target as HTMLInputElement;
    if (!input.files || input.files.length === 0) return;

    const file = input.files[0];
    this.alertMessage.set(null);

    // 5 MB max limit
    if (file.size > 5 * 1024 * 1024) {
      this.alertMessage.set({ type: 'error', text: 'Image size exceeds 5 MB. Please choose a smaller photo.' });
      input.value = '';
      return;
    }

    const validTypes = ['image/jpeg', 'image/png', 'image/webp', 'image/gif'];
    if (!validTypes.includes(file.type)) {
      this.alertMessage.set({ type: 'error', text: 'Invalid format. Allowed formats: JPG, PNG, WEBP, GIF.' });
      input.value = '';
      return;
    }

    // Immediate preview
    const reader = new FileReader();
    reader.onload = () => {
      this.previewAvatarUrl.set(reader.result as string);
    };
    reader.readAsDataURL(file);

    // Upload to server
    this.isUploadingAvatar.set(true);
    this.authService.uploadAvatar(file).subscribe({
      next: (res) => {
        this.isUploadingAvatar.set(false);
        this.profileForm.patchValue({ profilePictureUrl: res.url });
        this.alertMessage.set({ type: 'success', text: 'Profile photo uploaded! Remember to save changes.' });
      },
      error: (err) => {
        this.isUploadingAvatar.set(false);
        this.alertMessage.set({ type: 'error', text: err?.error?.message || 'Failed to upload photo.' });
      }
    });
  }

  removeAvatar(): void {
    this.previewAvatarUrl.set(null);
    this.profileForm.patchValue({ profilePictureUrl: null });
    this.alertMessage.set({ type: 'success', text: 'Profile photo removed. Save changes to apply.' });
  }

  onSaveProfile(): void {
    if (this.profileForm.invalid) {
      this.profileForm.markAllAsTouched();
      this.alertMessage.set({ type: 'error', text: 'Please correct the highlighted fields before saving.' });
      return;
    }

    this.isSubmittingProfile.set(true);
    this.alertMessage.set(null);

    const val = this.profileForm.value;
    const request: UpdateProfileRequest = {
      firstName: (val.firstName || '').trim(),
      lastName: (val.lastName || '').trim(),
      phoneNumber: filter10Digits(val.phoneNumber) || '',
      profilePictureUrl: val.profilePictureUrl ? val.profilePictureUrl.trim() : null,
      address: (val.address || '').trim() || null,
      city: (val.city || '').trim() || null,
      state: (val.state || '').trim() || null,
      postalCode: (val.postalCode || '').trim() || null
    };

    this.authService.updateProfile(request).subscribe({
      next: (updatedUser) => {
        this.isSubmittingProfile.set(false);
        this.alertMessage.set({ type: 'success', text: 'Your profile has been updated successfully.' });
      },
      error: (err) => {
        this.isSubmittingProfile.set(false);
        this.alertMessage.set({ type: 'error', text: err?.error?.message || 'Failed to update profile. Please try again.' });
      }
    });
  }

  onChangePassword(): void {
    if (this.passwordForm.invalid || this.isSameAsCurrentPassword || this.isPasswordMismatch) {
      this.passwordForm.markAllAsTouched();
      if (this.isSameAsCurrentPassword || this.passwordForm.hasError('sameAsCurrent')) {
        this.alertMessage.set({ type: 'error', text: 'New password cannot be the same as your current password.' });
      } else if (this.isPasswordMismatch || this.passwordForm.hasError('passwordMismatch')) {
        this.alertMessage.set({ type: 'error', text: 'New password and confirmation password do not match.' });
      } else {
        this.alertMessage.set({ type: 'error', text: 'Please fill in all password fields correctly.' });
      }
      return;
    }

    const val = this.passwordForm.value;
    this.isSubmittingPassword.set(true);
    this.alertMessage.set(null);

    const request: ChangePasswordRequest = {
      currentPassword: val.currentPassword,
      newPassword: val.newPassword,
      confirmPassword: val.confirmPassword
    };

    this.authService.changePassword(request).subscribe({
      next: () => {
        this.isSubmittingPassword.set(false);
        this.passwordForm.reset();
        this.alertMessage.set({ type: 'success', text: 'Password successfully updated! Closing...' });
        this.closeTimer = setTimeout(() => {
          this.close.emit();
        }, 700);
      },
      error: (err) => {
        this.isSubmittingPassword.set(false);
        this.alertMessage.set({ type: 'error', text: err?.error?.message || 'Failed to change password. Please check your current password.' });
      }
    });
  }

  ngOnDestroy(): void {
    if (this.closeTimer) {
      clearTimeout(this.closeTimer);
    }
  }

  onBackdropClick(event: MouseEvent): void {
    if ((event.target as HTMLElement).classList.contains('profile-modal-backdrop')) {
      this.close.emit();
    }
  }

  get userRoleBadge(): string {
    const user = this.currentUser();
    if (!user) return 'User';
    if (this.authService.isSuperAdmin()) return 'Super Admin';
    if (this.authService.isAdmin()) return 'Tenant Admin';
    if (this.authService.isServiceProvider()) return 'Specialist';
    return 'Customer';
  }
}

